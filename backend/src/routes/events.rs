use axum::{
    extract::{Path, Query, State},
    Json,
};
use serde::Deserialize;

use super::clean;
use crate::{
    due,
    error::{bad, ApiResult, AppError},
    models::{Event, EventInput},
    AppState,
};

#[derive(Deserialize)]
pub struct ListQuery {
    vehicle_id: Option<i64>,
    schedule_id: Option<i64>,
    year: Option<i32>,
}

pub async fn list(State(state): State<AppState>, Query(q): Query<ListQuery>) -> ApiResult<Vec<Event>> {
    let events: Vec<Event> = sqlx::query_as(
        "SELECT * FROM events
         WHERE (?1 IS NULL OR vehicle_id = ?1)
           AND (?2 IS NULL OR schedule_id = ?2)
           AND (?3 IS NULL OR strftime('%Y', date) = printf('%04d', ?3))
         ORDER BY date DESC, id DESC",
    )
    .bind(q.vehicle_id)
    .bind(q.schedule_id)
    .bind(q.year)
    .fetch_all(&state.db)
    .await?;
    Ok(Json(events))
}

fn validate(e: &EventInput) -> Result<(), AppError> {
    if e.title.trim().is_empty() {
        return Err(bad("Il titolo è obbligatorio"));
    }
    if e.km.is_some_and(|k| k < 0) || e.cost_cents.is_some_and(|c| c < 0) {
        return Err(bad("Km e costo non possono essere negativi"));
    }
    Ok(())
}

async fn check_schedule(state: &AppState, e: &EventInput) -> Result<(), AppError> {
    if let Some(sid) = e.schedule_id {
        let vid: Option<i64> = sqlx::query_scalar("SELECT vehicle_id FROM schedules WHERE id = ?")
            .bind(sid)
            .fetch_optional(&state.db)
            .await?;
        if vid != Some(e.vehicle_id) {
            return Err(bad("La scadenza non appartiene a questa auto"));
        }
    }
    Ok(())
}

/// Keeps the odometer reading generated by an event in sync with it.
async fn sync_reading(state: &AppState, event_id: i64, e: &EventInput) -> Result<(), AppError> {
    sqlx::query("DELETE FROM odometer_readings WHERE event_id = ?").bind(event_id).execute(&state.db).await?;
    if let Some(km) = e.km {
        sqlx::query("INSERT INTO odometer_readings (vehicle_id, event_id, date, km, source, note) VALUES (?, ?, ?, ?, 'event', ?)")
            .bind(e.vehicle_id)
            .bind(event_id)
            .bind(e.date)
            .bind(km)
            .bind(e.title.trim())
            .execute(&state.db)
            .await?;
    }
    Ok(())
}

pub async fn create(State(state): State<AppState>, Json(e): Json<EventInput>) -> ApiResult<Event> {
    validate(&e)?;
    check_schedule(&state, &e).await?;
    let ev: Event = sqlx::query_as(
        "INSERT INTO events (vehicle_id, schedule_id, title, category, date, km, cost_cents, provider, notes)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?) RETURNING *",
    )
    .bind(e.vehicle_id)
    .bind(e.schedule_id)
    .bind(e.title.trim())
    .bind(&e.category)
    .bind(e.date)
    .bind(e.km)
    .bind(e.cost_cents)
    .bind(clean(e.provider.clone()))
    .bind(clean(e.notes.clone()))
    .fetch_one(&state.db)
    .await?;
    sync_reading(&state, ev.id, &e).await?;
    if let Some(sid) = ev.schedule_id {
        due::recompute(&state.db, sid).await?;
    }
    Ok(Json(ev))
}

pub async fn update(State(state): State<AppState>, Path(id): Path<i64>, Json(e): Json<EventInput>) -> ApiResult<Event> {
    validate(&e)?;
    check_schedule(&state, &e).await?;
    let old: Event = sqlx::query_as("SELECT * FROM events WHERE id = ?").bind(id).fetch_one(&state.db).await?;
    let ev: Event = sqlx::query_as(
        "UPDATE events SET vehicle_id = ?, schedule_id = ?, title = ?, category = ?, date = ?, km = ?,
            cost_cents = ?, provider = ?, notes = ?
         WHERE id = ? RETURNING *",
    )
    .bind(e.vehicle_id)
    .bind(e.schedule_id)
    .bind(e.title.trim())
    .bind(&e.category)
    .bind(e.date)
    .bind(e.km)
    .bind(e.cost_cents)
    .bind(clean(e.provider.clone()))
    .bind(clean(e.notes.clone()))
    .bind(id)
    .fetch_one(&state.db)
    .await?;
    sync_reading(&state, id, &e).await?;
    for sid in [old.schedule_id, ev.schedule_id].into_iter().flatten() {
        due::recompute(&state.db, sid).await?;
    }
    Ok(Json(ev))
}

pub async fn delete(State(state): State<AppState>, Path(id): Path<i64>) -> ApiResult<serde_json::Value> {
    let old: Event = sqlx::query_as("SELECT * FROM events WHERE id = ?").bind(id).fetch_one(&state.db).await?;
    sqlx::query("DELETE FROM events WHERE id = ?").bind(id).execute(&state.db).await?;
    if let Some(sid) = old.schedule_id {
        due::recompute(&state.db, sid).await?;
    }
    Ok(Json(serde_json::json!({ "ok": true })))
}
